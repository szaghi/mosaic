"""Generate the command reference from the command line itself.

Every ``docs/reference/<command>.md`` gets an "Options" section, between ``<!-- cli:begin -->`` and
``<!-- cli:end -->`` markers, listing the arguments and options of the command and of its subcommands, as
``mosaic <command> --help`` prints them. The text around the markers is written by hand and kept; a page
without markers gets the section appended; a command without a page gets one. ``docs/reference/index.md``,
the map of the commands by area, is generated between the same markers.

Usage::

    python docs/scripts/gen_cli_reference.py            # write
    python docs/scripts/gen_cli_reference.py --check    # exit 1 when a page is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import typer.main

from mosaic.cli import app

REFERENCE = Path(__file__).resolve().parent.parent / "reference"
BEGIN, END = "<!-- cli:begin -->", "<!-- cli:end -->"
NOTE = "<!-- generated by docs/scripts/gen_cli_reference.py from the command line: do not edit -->"

# the map of the commands: every command must be in one area
AREAS = {
    "Finding papers": ["search", "similar", "watch", "cite"],
    "Getting PDFs": ["get", "import", "auth"],
    "Your library": ["cache", "index", "ask", "chat", "compare", "network"],
    "Elsewhere": ["ui", "notebook", "skill"],
    "Setup": ["config"],
}


# Duck typing, not isinstance(click.Group): typer >= 0.27 ships its own copy of click.
def _is_group(cmd: Any) -> bool:
    return hasattr(cmd, "commands")


def _is_option(p: Any) -> bool:
    return p.param_type_name == "option"


def page(name: str) -> str:
    """Page of a command: ``index`` would clash with the map of the commands."""
    return "index-command" if name == "index" else name


def root() -> Any:
    return typer.main.get_command(app)


def _cell(text: str) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    # URLs in help texts are examples (http://localhost:...): code, not links
    text = re.sub(r"(?<!`)(https?://[^\s)`]+)", r"`\1`", text)
    # placeholders such as /scidb/<DOI> are code too: bare, Vue reads them as
    # unclosed HTML tags and the docs build fails
    return re.sub(r"(?<![`\w/])([^\s()`]*<[A-Za-z][\w-]*>[^\s()`,;]*)", r"`\1`", text)


# click and typer's vendored click name the same types differently (INTEGER / INT)
_TYPES = {"STR": "TEXT", "STRING": "TEXT", "INT": "INTEGER", "BOOL": "BOOLEAN"}


def _value(p: Any) -> str:
    if _is_option(p) and (p.is_flag or p.count):
        return ""
    # word by word: IntRange is "integer range" in click, "int range" in typer's copy
    words = (p.type.name or "TEXT").upper().split()
    return f"`{' '.join(_TYPES.get(w, w) for w in words)}`"


def _default(p: Any) -> str:
    d = p.default
    if callable(d) or d is None or d == "" or d is False or d == () or d == []:
        return ""
    if d is True:
        return "on"
    return f"`{d}`"


def _help(p: Any) -> str:
    text = getattr(p, "help", None) or ""
    if _is_option(p) and p.multiple and "repeatable" not in text:
        text = text.rstrip(".") + " (repeatable)"
    return _cell(text)


def _usage(cmd: Any, path: list[str]) -> str:
    """``mosaic CMD [OPTIONS] ARG [OPT_ARG] MANY...``, built here: click versions render it differently."""
    pieces = ["[OPTIONS]"]  # --help, at least
    for a in (p for p in cmd.params if p.param_type_name == "argument"):
        name = a.name.upper()
        name = f"[{name}]" if not a.required else name
        pieces.append(f"{name}..." if a.nargs == -1 else name)
    return " ".join([*path, *pieces])


def _params(cmd: Any) -> list[str]:
    out: list[str] = []
    args = [p for p in cmd.params if p.param_type_name == "argument"]
    opts = [p for p in cmd.params if _is_option(p) and not p.hidden]
    if args:
        out += ["| Argument | Value | Description |", "|---|---|---|"]
        for a in args:
            req = "" if a.required else " (optional)"
            out.append(f"| `{a.human_readable_name.upper()}` | {_value(a)} | {_help(a)}{req} |")
        out.append("")
    if opts:
        out += ["| Option | Value | Default | Description |", "|---|---|---|---|"]
        for o in opts:
            names = ", ".join(f"`{n}`" for n in [*o.opts, *o.secondary_opts])
            out.append(f"| {names} | {_value(o)} | {_default(o)} | {_help(o)} |")
        out.append("")
    return out


def section(name: str, cmd: Any) -> str:
    lines = [NOTE, ""]
    if _is_group(cmd):
        for sub_name, sub in sorted(cmd.commands.items()):
            path = ["mosaic", name, sub_name]
            lines += [f"### `{' '.join(path)}`", "", _cell(sub.get_short_help_str(200)), ""]
            lines += ["```", _usage(sub, path), "```", ""]
            lines += _params(sub)
    else:
        lines += ["```", _usage(cmd, ["mosaic", name]), "```", ""]
        lines += _params(cmd)
    return "\n".join(lines).rstrip() + "\n"


def index_section(group: Any) -> str:
    lines = [NOTE, ""]
    for area, names in AREAS.items():
        lines += [f"## {area}", "", "| Command | What it does |", "|---|---|"]
        for n in names:
            lines.append(
                f"| [`mosaic {n}`](./{page(n)}) | {_cell(group.commands[n].get_short_help_str(200))} |"
            )
        lines.append("")
    lines += [
        "## Global options",
        "",
        "Put them before the command: `mosaic --verbose search ...`.",
        "",
    ]
    lines += _params(group)
    return "\n".join(lines).rstrip() + "\n"


def splice(text: str, body: str) -> str:
    block = f"{BEGIN}\n{body}{END}"
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        return head + block + rest.split(END, 1)[1]
    return text.rstrip() + "\n\n## Options\n\n" + block + "\n"


def pages() -> dict[Path, str]:
    group = root()
    listed = [n for names in AREAS.values() for n in names]
    missing = sorted(set(group.commands) - set(listed))
    if missing:
        raise SystemExit(f"commands not in AREAS: {', '.join(missing)}")
    out: dict[Path, str] = {}
    for name in listed:
        path = REFERENCE / f"{page(name)}.md"
        text = (
            path.read_text()
            if path.exists()
            else f"---\ntitle: mosaic {name}\n---\n\n# mosaic {name}\n"
        )
        out[path] = splice(text, section(name, group.commands[name]))
    path = REFERENCE / "index.md"
    text = path.read_text() if path.exists() else "---\ntitle: Commands\n---\n\n# Commands\n"
    out[path] = splice(text, index_section(group))
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="report stale pages, write nothing")
    args = parser.parse_args()
    stale = []
    for path, text in pages().items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for path in stale:
        print(f"{'stale' if args.check else 'wrote'}: {path.relative_to(REFERENCE.parent)}")
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
